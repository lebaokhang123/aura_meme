import {test,expect} from '@playwright/test';
test.skip(!process.env.AURA_AUTH_E2E_PREFIX,'Run through the guarded backend/tests/run_auth_browser.py runner');
test('real PostgreSQL registration, cookie login, reload, CSRF rejection and logout',async({page,context})=>{
 const name=process.env.AURA_AUTH_E2E_PREFIX,password='Synthetic-browser-password!';
 await page.goto('/register');
 await page.locator('#username').fill(name);await page.locator('#identifier').fill(name+'@example.com');
 await page.locator('#password').fill(password);await page.locator('#confirmPassword').fill(password);
 await page.locator('#terms').check();await page.locator('#loginForm button[type=submit]').click();
 await expect(page).toHaveURL(/\/login\?registered=1$/);
 await page.locator('#identifier').fill(name+'@example.com');await page.locator('#password').fill('wrong-password');
 await page.locator('#loginForm button[type=submit]').click();await expect(page.getByRole('alert')).toContainText('không đúng');
 await page.locator('#password').fill(password);await page.locator('#loginForm button[type=submit]').click();
 await expect(page).toHaveURL(/\/$/);await expect(page.locator('.account-avatar')).toBeVisible();
 const me=await page.request.get('/api/v1/users/me');expect(me.status()).toBe(200);
 expect((await me.json()).roles).toEqual(['USER']);
 const cookie=(await context.cookies()).find(row=>row.name==='am_session');
 expect(cookie.httpOnly).toBe(true);expect(cookie.sameSite).toBe('Lax');
 expect(await page.evaluate(()=>document.cookie)).not.toContain('am_session');
 expect(await page.evaluate(()=>JSON.stringify({local:localStorage,session:sessionStorage}))).not.toContain(password);
 await page.reload();await expect(page.locator('.account-avatar')).toBeVisible();
 expect((await page.request.get('/api/v1/admin/users')).status()).toBe(403);
 const denied=await page.evaluate(async()=> (await fetch('/api/v1/auth/logout',{method:'POST',credentials:'include'})).status);
 expect(denied).toBe(403);
 await page.getByRole('button',{name:'Mở menu tài khoản'}).click();
 await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();
 await expect(page.getByRole('button',{name:'Mở menu tài khoản'})).toHaveCount(0);
 expect((await page.request.get('/api/v1/users/me')).status()).toBe(401);
 await page.reload();await expect(page.getByRole('button',{name:'Mở menu tài khoản'})).toHaveCount(0);
});
