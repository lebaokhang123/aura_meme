import { expect, test, type Page } from '@playwright/test';

test('real draft refresh, upload, publish, pagination, comments and owner deletion', async ({ page, browser }) => {
  const prefix = process.env.AURA_E2E_PREFIX, image = process.env.AURA_E2E_IMAGE;
  if (!prefix || !image) throw new Error('Use the isolated backend/tests/run_browser.py runner.');
  const signIn = async (tab: Page, suffix: string) => {
    await tab.goto('/login');
    await tab.getByLabel('Email', { exact: true }).fill(prefix + suffix + '@example.com');
    await tab.getByLabel('Password', { exact: true }).fill('Synthetic blog password!');
    await tab.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(tab.getByRole('heading', { name: 'Account settings' })).toBeVisible();
  };
  await page.setViewportSize({ width: 1440, height: 900 });
  await signIn(page, '_blog');
  await page.goto('/posts/new');
  await page.getByLabel('Title', { exact: true }).fill('Synthetic E2E draft');
  await page.getByLabel('Content', { exact: true }).fill('Synthetic E2E written through the browser');
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: 'Synthetic E2E channel' });
  await page.getByLabel('Attach image (optional)').setInputFiles(image);
  await expect(page.getByRole('img', { name: 'Local preview of the selected attachment' })).toBeVisible();
  await page.getByRole('button', { name: 'Save post', exact: true }).click();
  await expect(page).toHaveURL(/\/my-posts\/[0-9a-f-]+$/);
  const id = page.url().split('/').at(-1)!;
  await expect(page.getByText('Draft saved.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Synthetic E2E draft');
  await expect(page.getByRole('combobox', { name: 'Post status', exact: true })).toHaveValue('draft');
  await expect(page.getByLabel('Remove existing private attachment')).not.toBeChecked();
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
    await page.screenshot({ path: test.info().outputPath('editor-polish-' + width + '.png'), fullPage: true });
  }
  expect((await page.request.get('/api/v1/posts/' + id)).status()).toBe(404);
  await page.getByLabel('Title', { exact: true }).fill('Synthetic E2E published');
  await page.getByRole('combobox', { name: 'Post status', exact: true }).selectOption('published');
  const changed = page.waitForRequest(request => request.method() === 'PATCH' && request.url().endsWith('/api/v1/posts/' + id));
  await page.getByRole('button', { name: 'Save post', exact: true }).click();
  expect((await changed).postDataJSON()).toEqual({ title: 'Synthetic E2E published', status: 'published' });
  await expect(page.getByRole('link', { name: 'View discussion', exact: true })).toBeVisible();
  await page.goto('/explore');
  await expect(page.getByRole('navigation', { name: 'Pagination' })).toContainText('22 results');
  await page.getByRole('button', { name: 'Next page', exact: true }).click();
  await expect(page).toHaveURL(/page=2/);
  await expect(page.getByRole('link', { name: 'Synthetic E2E paging 20', exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search posts', exact: true }).fill('Synthetic E2E published');
  await page.getByRole('button', { name: 'Search feed', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Pagination' })).toContainText('1 results');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: test.info().outputPath('explore-1440.png'), fullPage: true });
  await page.goto('/?search=Synthetic%20E2E%20published');
  await page.setViewportSize({ width: 375, height: 900 });
  await expect(page.getByRole('link', { name: 'Synthetic E2E published', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  await page.screenshot({ path: test.info().outputPath('home-375.png'), fullPage: true });
  await page.getByRole('link', { name: 'Synthetic E2E published', exact: true }).click();
  await page.getByLabel('Write a comment').fill('Synthetic E2E author comment');
  await page.getByRole('button', { name: 'Post comment', exact: true }).click();
  await expect(page.getByText('Synthetic E2E author comment', { exact: true })).toBeVisible();
  const second = await browser.newContext();
  const reader = await second.newPage();
  try {
    await signIn(reader, '_reader');
    await reader.goto('/my-posts/' + id);
    await expect(reader.getByRole('alert')).toContainText('not found');
    await expect(reader.getByRole('button', { name: 'Save post', exact: true })).toHaveCount(0);
    await reader.goto('/posts/' + id);
    await expect(reader.getByRole('link', { name: 'Edit post', exact: true })).toHaveCount(0);
    await reader.getByLabel('Write a comment').fill('Synthetic E2E reader comment');
    await reader.getByRole('button', { name: 'Post comment', exact: true }).click();
    await expect(reader.getByText('Synthetic E2E reader comment', { exact: true })).toBeVisible();
    await expect(reader.getByRole('button', { name: 'Delete comment', exact: true })).toHaveCount(1);
    reader.once('dialog', dialog => dialog.accept());
    await reader.getByRole('button', { name: 'Delete comment', exact: true }).click();
    await expect(reader.getByText('Synthetic E2E reader comment', { exact: true })).toHaveCount(0);
  } finally { await second.close(); }
  await page.reload();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete comment', exact: true }).click();
  await expect(page.getByText('No comments yet.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Edit post', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete post', exact: true }).click();
  await expect(page).toHaveURL(/\/my-posts$/);
  expect((await page.request.get('/api/v1/users/me/posts/' + id)).status()).toBe(404);
  expect((await page.request.get('/api/v1/posts/' + id)).status()).toBe(404);
});
