import { expect, test, type Page } from '@playwright/test';

test('real Guest/User Contact and Admin CRUD, roles, moderation, audit and last Admin guard', async ({ page, browser }) => {
  test.setTimeout(60_000); // This journey covers multiple CRUD sections; each assertion keeps its normal deadline.
  const prefix = process.env.AURA_E2E_PREFIX;
  if (!prefix) throw new Error('Use isolated backend/tests/run_browser.py.');
  const signIn = async (tab: Page, username: string, password = 'Synthetic blog password!') => {
    await tab.goto('/login');
    await tab.getByLabel('Email', { exact: true }).fill(username + '@example.com');
    await tab.getByLabel('Password', { exact: true }).fill(password);
    await tab.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(tab.getByRole('heading', { name: 'Account settings' })).toBeVisible();
  };
  const sendContact = async (tab: Page, name: string, email: string, body: string) => {
    await tab.goto('/contact');
    await tab.getByLabel('Your name').fill(name);
    await tab.getByLabel('Email address').fill(email);
    await tab.getByLabel('Subject').selectOption('feedback');
    await tab.getByLabel('Message', { exact: true }).fill(body);
    await tab.getByRole('button', { name: 'Send message', exact: true }).click();
    await expect(tab.getByRole('status')).toContainText('Message received. Reference:');
    await expect(tab.getByLabel('Message', { exact: true })).toHaveValue('');
  };
  await page.setViewportSize({ width: 1440, height: 900 });
  await sendContact(page, 'Synthetic E2E Guest', prefix + '_guest@example.com', 'Synthetic E2E guest message');
  const readerContext = await browser.newContext();
  const reader = await readerContext.newPage();
  try {
    await signIn(reader, prefix + '_reader');
    await sendContact(reader, 'Synthetic E2E Member', prefix + '_reader@example.com', 'Synthetic E2E member message');
    await reader.goto('/admin');
    await expect(reader.getByRole('heading', { name: 'Admin access required' })).toBeVisible();
    await signIn(page, prefix + '_admin');
    await page.goto('/admin?tab=contacts');
    await page.getByRole('button', { name: 'Review contact feedback', exact: true }).first().click();
    await page.getByRole('combobox', { name: 'Contact status', exact: true }).selectOption('resolved');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByRole('combobox', { name: 'Filter status', exact: true }).selectOption('resolved');
    await expect(page.getByRole('navigation', { name: 'Pagination' })).toContainText('1 results');
    await page.goto('/admin?tab=users');
    await page.getByRole('button', { name: 'Create user', exact: true }).click();
    await page.getByLabel('Username', { exact: true }).fill(prefix + '_created');
    await page.getByLabel('Account email', { exact: true }).fill(prefix + '_created@example.com');
    await page.getByLabel('Account display name', { exact: true }).fill('Synthetic E2E Created');
    await page.getByLabel('Initial password').fill('Synthetic admin-created password!');
    await page.getByRole('button', { name: 'Create record', exact: true }).click();
    const search = async (value: string) => {
      await page.getByRole('textbox', { name: 'Search records', exact: true }).fill(value);
      await page.getByRole('button', { name: 'Search admin', exact: true }).click();
    };
    await search(prefix + '_created');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_created', exact: true }).click();
    await page.getByLabel('Account display name', { exact: true }).fill('Synthetic E2E Updated');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('Synthetic E2E Updated');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_created', exact: true }).click();
    await page.getByRole('checkbox', { name: 'ADMIN role', exact: true }).check();
    await page.getByRole('button', { name: 'Save roles', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('ADMIN');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_created', exact: true }).click();
    await page.getByRole('checkbox', { name: 'ADMIN role', exact: true }).uncheck();
    await page.getByRole('button', { name: 'Save roles', exact: true }).click();
    await search(prefix + '_reader');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_reader', exact: true }).click();
    await page.getByRole('combobox', { name: 'Account status', exact: true }).selectOption('locked');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await reader.goto('/settings');
    await expect(reader).toHaveURL(/\/login$/);
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_reader', exact: true }).click();
    await page.getByRole('combobox', { name: 'Account status', exact: true }).selectOption('active');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await search(prefix + '_admin');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_admin', exact: true }).click();
    await page.getByRole('combobox', { name: 'Account status', exact: true }).selectOption('locked');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('conflicts');
    expect((await page.request.get('/api/v1/users/me')).status()).toBe(200);
    await page.getByRole('button', { name: 'Cancel editor', exact: true }).click();
    await search(prefix + '_created');
    await page.getByRole('button', { name: 'Edit user ' + prefix + '_created', exact: true }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Delete user', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('deleted');
    await page.goto('/admin?tab=categories');
    await page.getByRole('button', { name: 'Create category', exact: true }).click();
    await page.getByLabel('Category name', { exact: true }).fill('Synthetic E2E admin channel');
    await page.getByLabel('Category slug', { exact: true }).fill(prefix.replaceAll('_', '-') + '-admin');
    await page.getByRole('button', { name: 'Create record', exact: true }).click();
    await page.getByRole('button', { name: 'Edit category Synthetic E2E admin channel', exact: true }).click();
    await page.getByLabel('Category name', { exact: true }).fill('Synthetic E2E renamed channel');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByRole('button', { name: 'Edit category Synthetic E2E renamed channel', exact: true }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Hide category', exact: true }).click();
    await page.getByRole('combobox', { name: 'Filter status', exact: true }).selectOption('hidden');
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('Synthetic E2E renamed channel');
    await page.goto('/admin?tab=posts');
    await search('paging 00');
    await page.getByRole('button', { name: 'Edit post Synthetic E2E paging 00', exact: true }).click();
    await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('hidden');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByRole('button', { name: 'Edit post Synthetic E2E paging 00', exact: true }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Delete post', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('deleted');
    await page.goto('/admin?tab=audit-logs');
    await expect(page.getByRole('region', { name: 'Admin results' })).toContainText('contact.update');
    await expect(page.getByText('Synthetic E2E guest message', { exact: true })).toHaveCount(0);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: test.info().outputPath('admin-1440.png'), fullPage: true });
    await page.setViewportSize({ width: 375, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
    await page.screenshot({ path: test.info().outputPath('admin-375.png'), fullPage: true });
    for (const width of [375, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      await page.emulateMedia({ reducedMotion: 'reduce' });
      const region = page.getByRole('region', { name: 'Admin results' });
      await region.focus();
      await expect(region).toBeFocused();
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
      expect(await page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length)).toBe(0);
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: test.info().outputPath('admin-polish-' + width + '.png'), fullPage: true });
    }

  } finally { await readerContext.close(); }
});
